"""Hand-curated translation manuals, part 1: the chemical and astronomical revolutions.

Conventions (see README.md and the preface of Part II of the manuscript):
  term   = T(id, expression, role in T1, type-level image in T2, tokens)
           image: a string (one T2 expression), a list (partial denotation:
           several T2 expressions, none privileged), or None (no type-level image).
  token  = (letter, context of use in T1, T2 referent or None)
  infer  = (id, T1 inference, [term ids, with a token letter for terms that
           lack a type-level image], verdict)
           verdict: H holds in T2 when translated; R holds in T2 within a
           restricted domain or on one admissible reading; X is translated and
           denied by T2; U untranslatable (some term reading has no T2 referent).
  crit   = {criterion: (outcome, note)}; outcome '+' favoured the successor,
           '-' favoured the predecessor, '~' mixed or contested, '?' no claim made.
Referents are identified in the vocabulary of the successor theory as since
developed, which is what token reference in Kitcher's sense requires.
"""


def T(tid, term, role, image, tokens):
    return dict(id=tid, term=term, role=role, image=image, tokens=tokens)


