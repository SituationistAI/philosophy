"""Evaluation of the formulas of nd.py in the finite models of models.py.

Used as an independent cross-check: the axioms and the conclusions written in derivations.py are evaluated
directly from their syntax (property quantifiers range over Pi, positivity is membership in the filter
generated by the core), without the hand-coded intensions of models.py.
"""
import nd


class Evaluator:
    def __init__(self, M, defs):
        self.M = M
        self.defs = defs
        self.cache = {}

    def term(self, T, penv):
        """intension (bitmask) of a property term"""
        M = self.M
        if T[0] == "pv":
            return penv[T[1]]
        if T[0] == "pc":
            if T[1] not in self.cache:
                self.cache[T[1]] = self.term(self.defs[T[1]], {})
            return self.cache[T[1]]
        x, body = T[1], T[2]
        r = 0
        for w in range(M.n):
            for d in range(M.m):
                if self.ev(body, w, {x: d}, penv):
                    r |= M.pt(w, d)
        return r

    def ev(self, A, w, ienv, penv):
        M = self.M
        t = A[0]
        if t == "bot":
            return False
        if t == "app":
            return M.has(self.term(A[1], penv), w, ienv[A[2]])
        if t == "pos":
            return M.P(self.term(A[1], penv))
        if t in ("ess", "essS"):
            Yv, xv, body = self.defs[t]
            Yval = self.term(A[1], penv)
            return self.ev(body, w, {xv: ienv[A[2]]}, {Yv: Yval})
        if t == "not":
            return not self.ev(A[1], w, ienv, penv)
        if t == "and":
            return self.ev(A[1], w, ienv, penv) and self.ev(A[2], w, ienv, penv)
        if t == "or":
            return self.ev(A[1], w, ienv, penv) or self.ev(A[2], w, ienv, penv)
        if t == "imp":
            return (not self.ev(A[1], w, ienv, penv)) or self.ev(A[2], w, ienv, penv)
        if t == "iff":
            return self.ev(A[1], w, ienv, penv) == self.ev(A[2], w, ienv, penv)
        if t == "box":
            return all(self.ev(A[1], v, ienv, penv) for v in range(M.n) if (M.succ[w] >> v) & 1)
        if t == "dia":
            return any(self.ev(A[1], v, ienv, penv) for v in range(M.n) if (M.succ[w] >> v) & 1)
        if t == "all":
            return all(self.ev(A[2], w, {**ienv, A[1]: d}, penv) for d in range(M.m))
        if t == "ex":
            return any(self.ev(A[2], w, {**ienv, A[1]: d}, penv) for d in range(M.m))
        if t == "allp":
            return all(self.ev(A[2], w, ienv, {**penv, A[1]: Y}) for Y in M.Pi)
        if t == "exp":
            return any(self.ev(A[2], w, ienv, {**penv, A[1]: Y}) for Y in M.Pi)
        raise ValueError(A)

    def valid(self, A):
        """true at every world (closed formula)"""
        return all(self.ev(A, w, {}, {}) for w in range(self.M.n))
